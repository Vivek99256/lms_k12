'use client';

/**
 * One question in the question bank.
 *
 * The teacher bank and the student bank show the same question, correct option
 * and model answer; only the teacher gets Edit/Delete. Those come in through
 * `actions` so the read-only student card is the same component with the slot
 * left empty, and the two can never drift apart.
 *
 * Text goes through RichText rather than straight into dangerouslySetInnerHTML:
 * the bank now holds questions extracted from published books, which carry
 * LaTeX (`$x^2$`) and the occasional HTML table. Raw innerHTML would print the
 * LaTeX verbatim and trust markup that came out of a PDF.
 *
 * Only AI-generated questions wear their Bloom and difficulty tags on the
 * card face. Every question that has them carries Bloom/Difficulty (plus
 * Chapter/Concept/Category mapping and source attribution) behind the
 * drilldown chevron instead, so that metadata doesn't compete with the
 * question itself for attention and isn't split across a hover popup and a
 * click target.
 */
import { useState } from 'react';
import { CheckCircle2, ChevronDown, ImageOff, AlertTriangle, Sparkles } from 'lucide-react';

import { cn } from '@/lib/utils';
import { isLikelyJson, type QuestionBankItem } from '@/app/course-master/data/questionBank';
import RichText from './RichText';

function Pill({
  children,
  className,
  title,
}: {
  children: React.ReactNode;
  className?: string;
  title?: string;
}) {
  return (
    <span
      title={title}
      className={cn(
        'inline-flex items-center gap-1 rounded-full border px-2.5 py-1 text-[11px] font-bold',
        'border-slate-200 bg-slate-100 text-slate-600',
        className
      )}
    >
      {children}
    </span>
  );
}

export function QuestionBankQuestionCard({
  question,
  actions,
}: {
  question: QuestionBankItem;
  /** No longer shown on the card; still accepted so existing callers need no change. */
  visibleNumber?: number;
  actions?: React.ReactNode;
}) {
  const held = question.status === 0;
  const isAssertionReason = Boolean(question.assertion || question.reason);
  const isAiGenerated = question.source !== 'extracted';
  const hasModelAnswer = Boolean(question.modelAnswer) && !isLikelyJson(question.modelAnswer ?? '');
  // Where the question is filed: the chapter and concept it is mapped to, and its
  // learning-flow category. Only what the row actually carries is listed.
  const mappingRows: Array<[string, string]> = [];
  if (question.chapterTitle && question.chapterTitle !== 'Unknown Chapter') {
    mappingRows.push(['Chapter', question.chapterTitle]);
  }
  if (question.conceptTitle) mappingRows.push(['Concept', question.conceptTitle]);
  if (question.palCategory) mappingRows.push(['Category', question.palCategory]);
  // Previously shown in a hover tooltip next to the question-type pill; now folds
  // into the drilldown alongside Mapping so both live in one place. Concept is
  // left out here since Mapping above already carries it.
  const detailRows: Array<[string, string]> = [];
  if (question.bloom) detailRows.push(['Bloom', question.bloom]);
  if (question.difficulty) detailRows.push(['Difficulty', question.difficulty]);
  const hasOptions = Boolean(question.options && question.options.length > 0);
  const hasExtras =
    hasOptions ||
    hasModelAnswer ||
    mappingRows.length > 0 ||
    detailRows.length > 0 ||
    Boolean(question.attribution);
  const [showAnswer, setShowAnswer] = useState(false);

  return (
    <article
      className={cn(
        'rounded-[8px] border bg-white px-5 py-5 shadow-[0_2px_8px_rgba(15,23,42,0.08)] sm:px-6',
        held ? 'border-amber-300 bg-amber-50/30' : 'border-slate-200/90'
      )}
    >
      <div className="flex flex-col gap-3 sm:flex-row sm:items-start sm:justify-between">
        <div className="flex min-w-0 gap-4">
          <h3 className="min-w-0 text-[18px] font-bold leading-7 text-slate-950">
            {isAssertionReason ? (
              <span className="text-slate-500">Assertion &amp; Reason</span>
            ) : (
              <RichText
                as="span"
                value={question.question}
                className="inline [&_img]:max-w-full [&_img]:rounded-lg [&_table]:mt-2 [&_table]:border-collapse [&_td]:border [&_td]:border-slate-300 [&_td]:px-2 [&_td]:py-1 [&_th]:border [&_th]:border-slate-300 [&_th]:bg-slate-50 [&_th]:px-2 [&_th]:py-1"
              />
            )}
          </h3>
        </div>

        <div className="flex shrink-0 flex-wrap items-center justify-end gap-2 self-start">
          <Pill className="border-indigo-200 bg-[#eef2ff] text-[#3157ff]">
            {question.typeLabel ?? question.type}
          </Pill>

          {/* Generated questions wear their tags; a question from a book keeps
              them behind the info button above. */}
          {isAiGenerated ? (
            <>
              <Pill title="Generated by AI; no published source">
                <Sparkles size={11} />
                AI generated
              </Pill>
              {question.bloom && (
                <Pill className="border-blue-200 bg-blue-50 text-blue-700">
                  Bloom: {question.bloom}
                </Pill>
              )}
              {question.difficulty && (
                <Pill className="border-orange-200 bg-orange-50 text-orange-700">
                  Diff: {question.difficulty}
                </Pill>
              )}
            </>
          ) : null}

          <Pill>
            {question.marks} mark{question.marks === 1 ? '' : 's'}
          </Pill>

          {held && (
            <Pill
              className="border-amber-300 bg-amber-100 text-amber-800"
              title={
                question.validationStatus
                  ? `Validator: ${question.validationStatus}`
                  : 'Held for teacher review'
              }
            >
              <AlertTriangle size={11} />
              Held for review
            </Pill>
          )}

          {/* Opens the options, model answer and mapping below; all stay folded until pressed. */}
          {hasExtras ? (
            <button
              type="button"
              onClick={() => setShowAnswer((current) => !current)}
              aria-expanded={showAnswer}
              aria-label={showAnswer ? 'Hide answer details' : 'Show answer details'}
              title={showAnswer ? 'Hide answer details' : 'Show answer details'}
              className="inline-flex h-6 w-6 items-center justify-center rounded-full border border-slate-200 bg-white text-slate-500 transition-colors hover:border-slate-300 hover:text-slate-700"
            >
              <ChevronDown size={14} className={cn('transition-transform duration-300', showAnswer && 'rotate-180')} />
            </button>
          ) : null}
        </div>
      </div>

      {isAssertionReason && (
        <div className="mt-3 space-y-2">
          {question.assertion && (
            <div className="rounded-[6px] border-l-4 border-l-sky-400 bg-sky-50/60 px-4 py-2.5">
              <p className="text-xs font-bold uppercase tracking-[0.14em] text-sky-700">
                Assertion (A)
              </p>
              <RichText
                value={question.assertion}
                className="mt-1 text-[16px] leading-7 text-slate-800"
              />
            </div>
          )}
          {question.reason && (
            <div className="rounded-[6px] border-l-4 border-l-violet-400 bg-violet-50/60 px-4 py-2.5">
              <p className="text-xs font-bold uppercase tracking-[0.14em] text-violet-700">
                Reason (R)
              </p>
              <RichText
                value={question.reason}
                className="mt-1 text-[16px] leading-7 text-slate-800"
              />
            </div>
          )}
        </div>
      )}

      {question.subPartLabels && question.subPartLabels.length > 0 && (
        <p className="mt-2 text-xs text-slate-500">
          Sub-parts: {question.subPartLabels.join(', ')}
        </p>
      )}

      <QuestionFigures question={question} />

      {hasExtras ? (
        <QuestionExtras
          modelAnswer={hasModelAnswer ? question.modelAnswer ?? '' : ''}
          mappingRows={mappingRows}
          detailRows={detailRows}
          attribution={question.attribution ?? undefined}
          open={showAnswer}
        >
          {hasOptions ? (
            <div className="mt-4 space-y-2">
              {(question.options ?? []).map((option) => (
                <div
                  key={`${question.id}-${option.label}`}
                  className={cn(
                    'flex min-h-11 items-center gap-3 rounded-[6px] border px-3 text-[16px] transition-colors',
                    option.isCorrect
                      ? 'border-emerald-300 bg-emerald-50 text-emerald-800'
                      : 'border-slate-200 bg-white text-slate-900'
                  )}
                >
                  <span className="shrink-0 font-mono text-sm font-semibold text-slate-600">
                    {option.label}.
                  </span>
                  <RichText
                    as="span"
                    value={option.text}
                    className="min-w-0 flex-1 [&_img]:max-w-full [&_img]:rounded-lg [&_p]:inline"
                  />
                  {option.isCorrect ? (
                    <CheckCircle2 size={18} className="shrink-0 text-emerald-600" />
                  ) : null}
                </div>
              ))}
            </div>
          ) : null}
        </QuestionExtras>
      ) : null}

      {actions ? (
        <div className="mt-4 flex justify-end gap-3 border-t border-slate-200/80 pt-3">{actions}</div>
      ) : null}
    </article>
  );
}

/**
 * The options, model answer and mapping, folded away until the arrow beside
 * the question's badges is pressed. The body animates open (row height 0fr → 1fr
 * with a fade); `invisible` keeps the folded text out of the tab order and away
 * from screen readers, and the top margin lives inside the fold so a closed
 * block leaves no gap.
 */
function QuestionExtras({
  modelAnswer,
  mappingRows,
  detailRows,
  attribution,
  open,
  children,
}: {
  modelAnswer: string;
  mappingRows: Array<[string, string]>;
  /** Bloom/difficulty - previously a hover-only tooltip, now folded in alongside Mapping. */
  detailRows: Array<[string, string]>;
  attribution?: string;
  open: boolean;
  /** The MCQ options, shown first. */
  children?: React.ReactNode;
}) {
  const hasMapping = mappingRows.length > 0;
  const hasDetails = detailRows.length > 0;
  const hasMappingCard = hasMapping || hasDetails || Boolean(attribution);
  // Side by side on sm+; stacked with a horizontal divider on mobile instead of
  // the vertical one, so either layout always reads as one balanced block.
  const showBothColumns = hasMapping && hasDetails;

  return (
    <div
      aria-hidden={!open}
      className={cn(
        'grid transition-[grid-template-rows,opacity,visibility] duration-300 ease-out',
        open ? 'visible grid-rows-[1fr] opacity-100' : 'invisible grid-rows-[0fr] opacity-0'
      )}
    >
      <div className="min-h-0 overflow-hidden">
        {children}

        {modelAnswer ? (
          <div className="mt-4 rounded-[6px] border border-slate-200 border-l-4 border-l-[#4f46e5] bg-[#f3f7fc] px-4 py-3">
            <p className="text-xs font-bold uppercase tracking-[0.14em] text-slate-500">Model answer</p>
            <RichText
              value={modelAnswer}
              className="mt-2 text-[16px] leading-7 text-slate-700 [&_img]:max-w-full [&_img]:rounded-lg [&_table]:mt-2 [&_table]:border-collapse [&_td]:border [&_td]:border-slate-300 [&_td]:px-2 [&_td]:py-1"
            />
          </div>
        ) : null}

        {hasMappingCard ? (
          <div className="mt-3 rounded-[6px] border border-slate-200 border-l-4 border-l-emerald-500 bg-emerald-50/40 px-4 py-3">
            <div
              className={cn(
                showBothColumns && 'grid gap-4 sm:grid-cols-2 sm:gap-x-6 sm:divide-x sm:divide-emerald-200/70'
              )}
            >
              {hasMapping ? (
                <div className={cn(showBothColumns && 'sm:pr-6')}>
                  <p className="text-xs font-bold uppercase tracking-[0.14em] text-slate-500">Mapping</p>
                  <dl className="mt-2 grid gap-x-6 gap-y-1.5 text-[14px] sm:grid-cols-[max-content_1fr]">
                    {mappingRows.map(([label, value]) => (
                      <div key={label} className="contents">
                        <dt className="font-medium text-slate-500">{label}</dt>
                        <dd className="font-semibold text-slate-800">{value}</dd>
                      </div>
                    ))}
                  </dl>
                </div>
              ) : null}

              {hasDetails ? (
                <div
                  className={cn(
                    showBothColumns &&
                      'mt-4 border-t border-emerald-200/70 pt-4 sm:mt-0 sm:border-t-0 sm:pt-0 sm:pl-6'
                  )}
                >
                  <p className="text-xs font-bold uppercase tracking-[0.14em] text-slate-500">Details</p>
                  <dl className="mt-2 grid gap-x-6 gap-y-1.5 text-[14px] sm:grid-cols-[max-content_1fr]">
                    {detailRows.map(([label, value]) => (
                      <div key={label} className="contents">
                        <dt className="font-medium text-slate-500">{label}</dt>
                        <dd className="font-semibold text-slate-800">{value}</dd>
                      </div>
                    ))}
                  </dl>
                </div>
              ) : null}
            </div>

            {attribution ? (
              <p
                className={cn(
                  'text-[11px] leading-snug text-slate-500',
                  (hasMapping || hasDetails) && 'mt-3 border-t border-emerald-200/70 pt-2'
                )}
              >
                {attribution}
              </p>
            ) : null}
          </div>
        ) : null}
      </div>
    </div>
  );
}

function QuestionFigures({ question }: { question: QuestionBankItem }) {
  const figures = question.figures ?? [];

  if (figures.length === 0) {
    if (!question.figureRequired) return null;
    return (
      <div className="mt-3 flex items-center gap-2 rounded-[6px] border border-dashed border-amber-300 px-3 py-2 text-xs text-amber-700">
        <ImageOff size={14} />
        This question refers to a figure that was not captured during extraction.
      </div>
    );
  }

  return (
    <div className="mt-3 flex flex-wrap gap-3">
      {figures.map((figure, i) => (
        <QuestionFigure key={figure.sha256 ?? i} figure={figure} question={question} />
      ))}
    </div>
  );
}

/**
 * One figure, which may not load.
 *
 * Some rows still carry a URL from the machine that produced them, and a few
 * point at files that no longer exist. Rendering those as a broken-image icon
 * tells the reader nothing; the caption and the text OCR'd out of the figure
 * usually carry the data the question needs, so they are shown instead.
 */
function QuestionFigure({
  figure,
  question,
}: {
  figure: NonNullable<QuestionBankItem['figures']>[number];
  question: QuestionBankItem;
}) {
  const [failed, setFailed] = useState(false);
  const showImage = Boolean(figure.url) && !failed;

  if (!showImage && !figure.caption && !figure.ocr_text) {
    return (
      <div className="flex items-center gap-2 rounded-[6px] border border-dashed border-slate-300 px-3 py-2 text-xs text-slate-500">
        <ImageOff size={14} />
        Figure unavailable.
      </div>
    );
  }

  return (
    <figure className="overflow-hidden rounded-[6px] border border-slate-200 bg-white">
      {showImage ? (
        /* eslint-disable-next-line @next/next/no-img-element */
        <img
          src={figure.url as string}
          alt={figure.caption || `Figure for question ${question.displayId}`}
          loading="lazy"
          onError={() => setFailed(true)}
          className="max-h-56 w-auto max-w-full object-contain"
        />
      ) : (
        <div className="flex items-center gap-2 px-3 py-2 text-[11px] text-slate-500">
          <ImageOff size={13} />
          Figure couldn’t be loaded
        </div>
      )}
      {(figure.caption || figure.ocr_text) && (
        <figcaption className="max-w-[280px] space-y-0.5 px-2 py-1 text-[11px] leading-snug text-slate-500">
          {figure.caption && <span className="block">{figure.caption}</span>}
          {figure.ocr_text && (
            <span
              className={failed ? 'block text-slate-600' : 'block line-clamp-3 text-slate-400'}
              title={figure.ocr_text}
            >
              Read from image: {figure.ocr_text}
            </span>
          )}
        </figcaption>
      )}
    </figure>
  );
}
